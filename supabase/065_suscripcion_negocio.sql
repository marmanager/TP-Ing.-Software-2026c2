-- 065_suscripcion_negocio.sql — la suscripción la paga el negocio
--
-- Correr entero en el SQL Editor de Supabase. Es idempotente.
-- Va después de las de development (hasta 064_lista_de_categorias).
--
-- Las tres tablas existían, creadas a mano desde el panel para las rutas
-- /payments/suscription y /payments/webhookMP. Acá quedan versionadas: en
-- la base de producción los "create table if not exists" no hacen nada.
--
-- QUIÉN PAGA: el negocio. Paga el dueño y entra todo el equipo. usuario_id
-- queda como quién pagó; lo que da acceso es negocio_id con estado
-- 'authorized' (el estado lo pisa el webhook con el de Mercado Pago).
-- Escribe sólo la API, con service_role: nadie se marca pago desde el front.
-- ============================================================

-- ------------------------------------------------------------
-- 1. Las tablas como estaban
-- ------------------------------------------------------------
create table if not exists suscripcion (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  nombre      text not null,
  descripcion text not null
);

create table if not exists suscripcion_precio (
  id             bigint generated by default as identity primary key,
  created_at     timestamptz not null default now(),
  suscripcion_id bigint not null references suscripcion(id),
  moneda         text not null,
  precio         numeric not null
);

create table if not exists usuario_suscripcion (
  id             bigint generated by default as identity primary key,
  created_at     timestamptz not null default now(),
  usuario_id     uuid not null references usuario(id),
  suscripcion_id bigint not null references suscripcion(id),
  proveedor      text not null,
  proveedor_id   text not null,
  estado         text not null
);

-- ------------------------------------------------------------
-- 2. La suscripción es del negocio
-- ------------------------------------------------------------
-- Nullable: las filas viejas, si hay, eran por usuario y no tienen negocio.
alter table usuario_suscripcion
  add column if not exists negocio_id uuid references negocio(id) on delete cascade;

create index if not exists usuario_suscripcion_negocio_idx
  on usuario_suscripcion (negocio_id, estado);

-- ------------------------------------------------------------
-- 3. RLS
-- ------------------------------------------------------------
-- Los planes y sus precios son la vitrina: los ve cualquiera, también la
-- landing sin sesión. La suscripción la ve sólo el equipo del negocio.
-- Sin políticas de insert/update/delete: escribe sólo service_role.
alter table suscripcion enable row level security;
alter table suscripcion_precio enable row level security;
alter table usuario_suscripcion enable row level security;

drop policy if exists suscripcion_la_ve_cualquiera on suscripcion;
create policy suscripcion_la_ve_cualquiera on suscripcion
  for select to anon, authenticated using (true);

drop policy if exists suscripcion_precio_lo_ve_cualquiera on suscripcion_precio;
create policy suscripcion_precio_lo_ve_cualquiera on suscripcion_precio
  for select to anon, authenticated using (true);

drop policy if exists usuario_suscripcion_la_ve_el_negocio on usuario_suscripcion;
create policy usuario_suscripcion_la_ve_el_negocio on usuario_suscripcion
  for select to authenticated using (negocio_id = mi_negocio());

-- ------------------------------------------------------------
-- 4. El plan
-- ------------------------------------------------------------
-- Sólo si no hay ninguno. AJUSTAR el precio antes de correrla.
insert into suscripcion (nombre, descripcion)
select 'Mensual', 'Acceso completo para todo el equipo del negocio.'
where not exists (select 1 from suscripcion);

insert into suscripcion_precio (suscripcion_id, moneda, precio)
select s.id, 'ARS', 10000
from suscripcion s
where s.nombre = 'Mensual'
  and not exists (select 1 from suscripcion_precio p where p.suscripcion_id = s.id and p.moneda = 'ARS');
